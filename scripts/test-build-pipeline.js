const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { root, VERSION, VERSION_PLACEHOLDER, readSource } = require("./source-loader");
const { sourceFiles } = require("./build.js");

const compiledRoot = path.join(root, "dist", "compiled");
const bundlePath = path.join(root, "re_om_midi.jsx");

function walkJsFiles(dir, results) {
  fs.readdirSync(dir, { withFileTypes: true }).forEach((entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkJsFiles(fullPath, results);
      return;
    }
    if (entry.isFile() && entry.name.endsWith(".js")) {
      results.push(fullPath);
    }
  });
}

assert.ok(fs.existsSync(compiledRoot), "dist/compiled should exist after tsc + rename-js-to-jsx");
assert.ok(fs.existsSync(bundlePath), "re_om_midi.jsx should exist after scripts/build.js");

const leftoverJs = [];
walkJsFiles(compiledRoot, leftoverJs);
assert.strictEqual(leftoverJs.length, 0, "compiled output should be .jsx only, found: " + leftoverJs.join(", "));

sourceFiles.forEach((relativePath) => {
  const absolutePath = path.join(root, relativePath);
  assert.ok(fs.existsSync(absolutePath), "missing compiled file: " + relativePath);
  assert.ok(relativePath.endsWith(".jsx"), "compiled bundle inputs should use .jsx: " + relativePath);
  assert.ok(fs.statSync(absolutePath).size > 0, "compiled file should not be empty: " + relativePath);
});

const namespaceOnDisk = fs.readFileSync(path.join(root, "dist/compiled/core/namespace.jsx"), "utf8");
assert.ok(
  namespaceOnDisk.includes(VERSION_PLACEHOLDER),
  "compiled namespace on disk should keep the version placeholder for build-time substitution"
);
assert.ok(
  !namespaceOnDisk.includes('api.VERSION = "' + VERSION + '"'),
  "compiled namespace on disk should not bake package.json version directly"
);

const namespaceFromLoader = readSource("dist/compiled/core/namespace.jsx");
assert.ok(
  namespaceFromLoader.includes('api.VERSION = "' + VERSION + '"'),
  "readSource should substitute VERSION placeholder when bundling or testing"
);
assert.ok(
  namespaceFromLoader.indexOf(VERSION_PLACEHOLDER) < 0,
  "readSource should remove VERSION placeholder after substitution"
);

const bundleSource = fs.readFileSync(bundlePath, "utf8");
assert.ok(bundleSource.indexOf("ReOm MIDI v" + VERSION) >= 0, "bundle banner should include package version");
assert.ok(
  bundleSource.indexOf("Generated by scripts/build.js from TypeScript sources in src/") >= 0,
  "bundle banner should identify the TypeScript build pipeline"
);

const sectionPattern = /\/\/ ---- (dist\/compiled\/[^\s]+) ----/g;
const bundleSections = [];
let sectionMatch;
while ((sectionMatch = sectionPattern.exec(bundleSource)) !== null) {
  bundleSections.push(sectionMatch[1]);
}
assert.deepStrictEqual(bundleSections, sourceFiles, "bundle section order should match scripts/build.js sourceFiles");

const forbiddenPatterns = [
  { pattern: /\bObject\.assign\b/, label: "Object.assign" },
  { pattern: /=>/, label: "arrow functions" },
  { pattern: /\bconst\s+[A-Za-z_$]/, label: "const declarations" },
  { pattern: /\blet\s+[A-Za-z_$]/, label: "let declarations" }
];
forbiddenPatterns.forEach(({ pattern, label }) => {
  assert.ok(!pattern.test(bundleSource), "bundle should not contain " + label + " (ExtendScript ES3)");
});

console.log("Build pipeline test passed (" + sourceFiles.length + " compiled files, bundle ES3-safe).");
